/**
 * Retorna um user agent aleatório da lista
 * @returns {string} User agent aleatório
 */
const getRandomUserAgent = () => {
  const randomIndex = Math.floor(Math.random() * userAgents.length);
  return userAgents[randomIndex];
};

module.exports = {
  userAgents,
  getRandomUserAgent
};